(async () => {
  const results = [];
  const platform = window.QieJi.platform;
  const invoke = (action, payload = null) => window.__TAURI__.core.invoke("qieji_smoke", { action, payload });
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const frames = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  const check = (name, valid) => { results.push({ name, valid: Boolean(valid) }); if (!valid) throw new Error(name); };
  const current = () => window.paperEdgePrepareToQuit();
  const add = async text => {
    const input = document.querySelector('.task-input');
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, text);
    input.dispatchEvent(new Event('input', { bubbles: true }));
    await frames(); document.querySelector('.add-button').click(); await frames();
    return current().tasks.find(t => t.text === text);
  };
  try {
    await frames(); await platform.flush(); await document.fonts.ready;
    check('fresh-window-shows-only-five-generic-samples', current().tasks.length === 5 && current().tasks.every(t=>t.id.startsWith('sample-')));
    check('phase-one-has-no-unavailable-controls', !document.querySelector('.mode-switch,.toolbar-print,.row-action.reminder,[aria-label="收起到侧边"]'));
    check('bundled-font-loaded', document.fonts.check('16px "QieJi Paper"'));
    const task = await add('原生保存合成任务'); check('add-task-in-real-react-view', Boolean(task));
    let row = document.querySelector(`[data-task-id="${task.id}"]`); row.querySelector('.task-copy').click(); await frames();
    const editor = document.querySelector('.task-edit'); editor.innerHTML = '<b>退出前未失焦的合成编辑</b>';
    editor.dispatchEvent(new Event('input', { bubbles: true }));
    await platform.saveCurrent();
    let native = (await invoke('read')).workspace.tasks.find(t=>t.id===task.id);
    check('unblurred-edit-flushed-and-saved-with-formatting', native.text==='退出前未失焦的合成编辑' && /<(b|strong)>/.test(native.html));
    row = document.querySelector(`[data-task-id="${task.id}"]`); row.querySelector('.task-check').click(); await frames(); await platform.flush();
    check('completed-task-is-saved', (await invoke('read')).workspace.tasks.find(t=>t.id===task.id).done);
    row.querySelector('.row-action.delete').click(); await frames(); await platform.flush();
    check('delete-keeps-recoverable-record', (await invoke('read')).workspace.trash.some(t=>t.task.id===task.id));
    document.querySelector('.recovery-button').click(); await frames();
    [...document.querySelectorAll('.restore-button')].find(b=>b.textContent==='恢复').click(); await frames(); await platform.flush();
    check('restore-keeps-text-format-and-completion', (await invoke('read')).workspace.tasks.some(t=>t.id===task.id && t.done && t.html));
    document.querySelector('.recovery-button').click(); await frames();
    check('export-command-completes', await platform.exportWorkspace());
    const exported = (await invoke('read')).exported;
    check('export-includes-workspace-and-rich-text', exported.format==='qieji-workspace' && exported.tasks.some(t=>t.id===task.id&&t.html));
    check('import-command-completes', await platform.importWorkspace());
    let persisted = await invoke('read');
    check('import-merges-and-checkpoints-original', persisted.workspace.tasks.some(t=>t.id==='imported-native') && persisted.backups===1);
    await platform.importWorkspace(); persisted=await invoke('read');
    check('same-id-import-does-not-duplicate', persisted.workspace.tasks.filter(t=>t.id==='imported-native').length===1);
    await invoke('failWrites', true);
    const unsaved = await add('写入失败后仍保留的合成任务');
    check('failed-save-cancels-native-exit', await platform.requestClose()===false);
    check('failed-save-state-is-error', platform.getSaveState().status==='error');
    check('failed-save-retains-in-memory-content', current().tasks.some(t=>t.id===unsaved.id));
    await frames();
    check('failed-save-shows-retry-after-react-commit', Boolean(document.querySelector('.save-status.is-error')));
    check('failed-write-does-not-replace-native-file', !(await invoke('read')).workspace.tasks.some(t=>t.id===unsaved.id));
    await platform.exportWorkspace(); check('failed-save-can-still-export', (await invoke('read')).exported.tasks.some(t=>t.id===unsaved.id));
    await invoke('failWrites', false); await platform.saveCurrent();
    check('retry-persists-the-retained-task', (await invoke('read')).workspace.tasks.some(t=>t.id===unsaved.id) && platform.getSaveState().status==='saved');
    const reloaded = await window.__TAURI__.core.invoke('qieji_bootstrap');
    check('native-reload-reads-the-saved-workspace', reloaded.workspace.tasks.some(t=>t.id===unsaved.id) && reloaded.workspace.tasks.some(t=>t.id===task.id));
  } catch (error) { results.push({ name: 'runtime-error', valid: false, error: String(error?.stack || error) }); }
  await invoke('result', { valid: results.every(r=>r.valid), results });
})();
